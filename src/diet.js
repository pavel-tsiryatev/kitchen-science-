// Фильтр блюд «без…» по составу рецепта. Ингредиенты «по желанию» не считаются,
// а в «А или Б» достаточно, чтобы подходил хотя бы один вариант («Вода или бульон»).

export const DIETS = [
  {
    id: 'nomeat', title: 'Без мяса и рыбы',
    re: /мяс|стейк|филе|копч|пельмен|говя|свин|баран|телят|фарш|кур(иц|ин)|крылыш|бёдр|бедр|окороч|индейк|утк|бекон|грудинк|колбас|сосиск|ветчин|рульк|ножк|печень(?!е)|бульон|рыб|скумбр|лосос|треск|минтай|хек|судак|тунец|тунц|сельд|анчоус|креветк|кальмар|желатин/,
  },
  {
    id: 'noegg', title: 'Без яиц',
    re: /яйц|яйко|желтк|майонез|пельмен|лапша домашн|листы для лазаньи/,
  },
  {
    id: 'nodairy', title: 'Без молочного',
    re: /(?<!кокосовое )молок|сливк|сливочн|сметан|творог|творож|сыр|моцарел|пармезан|сулугуни|фета|брынз|кефир|йогурт|ряженк|простокваш|сгущ|плавлен/,
  },
  {
    id: 'nogluten', title: 'Без глютена',
    re: /мук[аи](?! (рисов|кукуруз|гречнев))|мука$|хлеб|батон|сухар|гренк|макарон|(?<!(томатная|кунжутная|ореховая) )паст[аы]|спагетти|тальятелле|феттучине|лапш|лазань|пельмен|вареник|булгур|кускус|манк|перлов|овсян|ячмен|пшениц|солод|дрожжевое тесто|слоёное тесто|соевый соус|сейтан|панировочн|печенье/,
  },
];

const OPTIONAL = /по желанию|для подачи|для украшения/i;

/** Подходит ли один ингредиент под диету: хотя бы один вариант из «А или Б» без запрещённого */
function itemOk(name, re) {
  const clean = name.toLowerCase().replace(/ё/g, 'е').replace(/\s*\((?![^)]*(?:по желанию|для подачи))[^)]*\)/g, '');
  if (OPTIONAL.test(name)) return true;
  return clean.split(/\s+или\s+/).some(part => !re.test(part));
}

// регулярные выражения пишем через «ё», а сравниваем без неё
const norm = re => new RegExp(re.source.replace(/ё/g, 'е'), re.flags);
const RULES = Object.fromEntries(DIETS.map(d => [d.id, norm(d.re)]));

/** Подходит ли блюдо под все выбранные ограничения. Статьи без ингредиентов не подходят. */
export function fitsDiets(article, ids) {
  if (!ids?.length) return true;
  const items = article?.ingredients?.items;
  // «Начинка» без уточнения — состав неизвестен, такое блюдо не предлагаем
  if (!items?.length || items.some(it => /^начинка/i.test(it.name))) return false;
  return ids.every(id => {
    const re = RULES[id];
    return !re || items.every(it => itemOk(it.name, re));
  });
}

/** Какие ингредиенты мешают (для подсказки и тестов) */
export function blockers(article, id) {
  const re = RULES[id];
  return (article?.ingredients?.items || []).filter(it => !itemOk(it.name, re)).map(it => it.name);
}

export const DIET_IDS = DIETS.map(d => d.id);
